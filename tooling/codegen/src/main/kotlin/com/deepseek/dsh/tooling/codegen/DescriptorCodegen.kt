package com.deepseek.dsh.tooling.codegen

import kotlinx.serialization.Serializable

/**
 * v4.0 设计文档 §5.2:
 * ctx.typert.local 导出 InvocationDescriptor IR 数据结构
 */
@Serializable
data class InvocationDescriptor(
    val name: String,
    val method: String = "POST",
    val path: String = "/api",
    val description: String? = null,
    val requestSchema: String? = null,
    val responseSchema: String? = null,
    val digest: String
)

@Serializable
data class DescriptorSet(
    val version: String,
    val setDigest: String,
    val endpoints: List<InvocationDescriptor> = emptyList()
)

object KotlinCodeGenerator {

    fun generateClientInterface(set: DescriptorSet, packageName: String): String {
        val sb = StringBuilder()
        sb.appendLine("// Auto-generated by :tooling:codegen. DO NOT EDIT.")
        sb.appendLine("// Input digest: ${set.setDigest}")
        sb.appendLine("package $packageName")
        sb.appendLine()
        sb.appendLine("import com.deepseek.dsh.core.protocol.RemoteResult")
        sb.appendLine()
        sb.appendLine("interface GeneratedDshRemoteEndpoints {")

        for (ep in set.endpoints) {
            val funName = ep.name.replace(".", "_")
            ep.description?.let {
                sb.appendLine("    /** $it */")
            }
            sb.appendLine("    suspend fun $funName(params: Map<String, String>): RemoteResult<String>")
        }

        sb.appendLine("}")
        return sb.toString()
    }
}
